// Screenshots for 1.7.0's new screens: developer mode guide, Older Samsung, Fire TV connect and plan.
"use strict";
const { chromium } = require("/opt/npm-tools/node_modules/playwright");
const { spawn } = require("node:child_process");
const fs = require("node:fs");
const path = require("node:path");
const os = require("node:os");
(async () => {
  const data = fs.mkdtempSync(path.join(os.tmpdir(), "uishots-"));
  const out = process.argv[2] || "/tmp/shots170";
  fs.mkdirSync(out, { recursive: true });
  const mockProc = spawn(process.execPath, [path.join(__dirname, "run-mock-fire.js")], { stdio: "inherit" });
  const server = spawn(process.execPath, ["server.js"], { cwd: path.join(__dirname, "..", "nodejs-project"), env: { ...process.env, NUVIO_DATA_DIR: data, NUVIO_UI_PORT: "4798", NUVIO_TOKEN: "tok" }, stdio: ["ignore", "inherit", "inherit"] });
  await new Promise((r) => setTimeout(r, 2500));
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 400, height: 860 }, deviceScaleFactor: 2 });
  const errors = [];
  page.on("pageerror", (e) => { errors.push(e.message); console.log("PAGE ERROR", e.message); });
  await page.goto("http://127.0.0.1:4798/?t=tok");
  await page.waitForTimeout(1500);
  await page.click("#ok"); await page.waitForTimeout(300);
  await page.screenshot({ path: `${out}/1-pick.png`, fullPage: true });
  await page.click("#guide-btn"); await page.waitForTimeout(300);
  await page.click("details.help:nth-of-type(8) > summary").catch(() => {});
  await page.evaluate(() => { const d = [...document.querySelectorAll("details.help")]; d.forEach((x) => { if (/Fire TV/.test(x.textContent.slice(0, 60))) x.open = true; }); });
  await page.waitForTimeout(200);
  await page.screenshot({ path: `${out}/2-guide-fire.png`, fullPage: true });
  await page.click("#back"); await page.waitForTimeout(300);
  await page.click('[data-profile="samsung-old"]'); await page.waitForTimeout(300);
  await page.screenshot({ path: `${out}/3-old-empty.png`, fullPage: true });
  await page.fill("#old-model", "UN46F6400"); await page.dispatchEvent("#old-model", "change"); await page.waitForTimeout(700);
  await page.screenshot({ path: `${out}/4-old-2013.png`, fullPage: true });
  await page.click('[data-year="2016"]'); await page.waitForTimeout(700);
  await page.evaluate(() => document.querySelectorAll("details.help").forEach((x) => { x.open = true; }));
  await page.screenshot({ path: `${out}/5-old-2016.png`, fullPage: true });
  await page.click("#ok"); await page.waitForTimeout(300);
  await page.click('[data-profile="firetv"]'); await page.waitForTimeout(300);
  await page.fill("#ip", "127.0.0.1:25559"); await page.dispatchEvent("#ip", "change"); await page.waitForTimeout(800);
  await page.evaluate(() => document.querySelectorAll("details.help").forEach((x) => { x.open = true; }));
  await page.screenshot({ path: `${out}/6-fire-connect.png`, fullPage: true });
  await page.click("#ok"); await page.waitForTimeout(3000);
  await page.screenshot({ path: `${out}/7-fire-plan.png`, fullPage: true });
  await page.click("#open-settings"); await page.waitForTimeout(600);
  await page.screenshot({ path: `${out}/8-settings.png`, fullPage: false });
  await browser.close(); server.kill(); mockProc.kill();
  console.log("shots in", out, "errors:", errors.length);
  process.exit(errors.length ? 1 : 0);
})().catch((e) => { console.error(e); process.exit(1); });
